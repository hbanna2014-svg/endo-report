/** 320x240 dark-blue endoscopic-looking placeholder frame with a label. */
function pngFrame(seed = 0) {
  // A tiny valid PNG is enough for storage tests, but for a demonstration the
  // 3x3 gradient PNG below is generated by hand so no image library is needed.
  const zlib = require('node:zlib')
  const W = 320
  const H = 240
  const raw = Buffer.alloc((W * 3 + 1) * H)
  let p = 0
  for (let y = 0; y < H; y += 1) {
    raw[p++] = 0 // filter type
    for (let x = 0; x < W; x += 1) {
      const r = Math.round(90 + 60 * Math.sin((x + seed * 30) / 40) + 25 * Math.cos(y / 25))
      const g = Math.round(55 + 40 * Math.cos((x + y + seed * 20) / 55))
      const b = Math.round(70 + 30 * Math.sin((y + seed * 10) / 30))
      raw[p++] = Math.max(0, Math.min(255, r))
      raw[p++] = Math.max(0, Math.min(255, g))
      raw[p++] = Math.max(0, Math.min(255, b))
    }
  }
  const idat = zlib.deflateSync(raw)

  const chunk = (type, data) => {
    const len = Buffer.alloc(4)
    len.writeUInt32BE(data.length, 0)
    const typeBuf = Buffer.from(type, 'latin1')
    const crcInput = Buffer.concat([typeBuf, data])
    const crc = Buffer.alloc(4)
    crc.writeUInt32BE(crc32(crcInput) >>> 0, 0)
    return Buffer.concat([len, typeBuf, data, crc])
  }

  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(W, 0)
  ihdr.writeUInt32BE(H, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 2 // colour type: truecolour
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
  return Buffer.concat([signature, chunk('IHDR', ihdr), chunk('IDAT', idat), chunk('IEND', Buffer.alloc(0))])
}

let CRC_TABLE = null
function crc32(buf) {
  if (!CRC_TABLE) {
    CRC_TABLE = new Int32Array(256)
    for (let n = 0; n < 256; n += 1) {
      let c = n
      for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
      CRC_TABLE[n] = c
    }
  }
  let c = -1
  for (let i = 0; i < buf.length; i += 1) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8)
  return c ^ -1
}

